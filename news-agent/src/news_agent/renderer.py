"""Render English announcements and a tightly bounded README block."""

from __future__ import annotations

import difflib
import html
import re

from .contract import Entry
from .web import METRICS, node_label, render_banner, render_page, task_label

START = "<!-- SURE-NEWS:START -->"
END = "<!-- SURE-NEWS:END -->"
GENERATED = "<!-- generated by news-agent; do not edit inside this block -->"


def text(value: str) -> str:
    value = html.escape(value)
    return re.sub(r"([*_~|])", r"\\\1", value)


def replace_block(readme: str, block: str) -> str:
    if readme.count(START) != 1 or readme.count(END) != 1:
        raise ValueError("README needs exactly one SURE-NEWS marker pair")
    start, end = readme.index(START), readme.index(END)
    if end < start:
        raise ValueError("Reversed README news markers")
    return readme[:start] + START + "\n" + block + "\n" + readme[end:]


def outside_block(readme: str) -> str:
    return replace_block(readme, "")


def section(entry: Entry, *, prefix: str, short: bool = False) -> str:
    title = text(entry.title)
    lines = [f"<a id=\"{entry.id}\"></a>", "",
             f"### {title}", "",
             f"<kbd>Supported</kbd> &nbsp; {entry.published_at.strftime('%d %b %Y')}", "",
             text(entry.summary), "",
             "| Task | Metric | Evaluation path |",
             "| :--- | :--- | :--- |"]
    for chain in entry.chain:
        metric = METRICS.get(chain.metric, chain.metric)
        lang = "" if chain.language == "n/a" else f" / {chain.language}"
        path = " → ".join(text(node_label(n.id)) for n in chain.nodes) + " → `report.json`"
        lines.append(f"| **{text(task_label(chain.task))}{text(lang)}** | **{text(metric)}** | {path} |")
    lines += ["", "<details>", "<summary>Exact pipeline IDs &amp; versioned nodes</summary>", ""]
    for chain in entry.chain:
        lines += [f"**{text(task_label(chain.task))} / {text(METRICS.get(chain.metric, chain.metric))}**", "",
                  f"```text\n{chain.pipeline_id}\n```", "",
                  " → ".join(f"`{n.id}` ({text(n.version)})" for n in chain.nodes) + " → `report.json`", ""]
    lines += ["</details>", ""]
    if not short:
        lines += ["> **Before you run**", ">", "> " + text(entry.limitations), ""]
    docs = " · ".join(f"[{path.split('/')[-1][:-3]}]({prefix}{path})"
                      for path in entry.links.docs)
    # Evidence tests are pinned to the source commit.  They may not exist in
    # the checkout used to render a preview (for example, a fork can lag the
    # source branch), so keep these links anchored to the verified commit.
    repository = entry.links.source_change.rsplit("/commit/", 1)[0]
    tests = " · ".join(
        f"[{path.split('/')[-1]}]({repository}/blob/{entry.evidence.source_commit}/{path})"
        for path in entry.links.tests
    )
    history = "index.md"
    full = f"{prefix}docs/news/{history}#{entry.id}"
    lines += [f"[Full announcement]({full}) · Task docs: {docs} · "
              f"[Catalog]({prefix}{entry.links.catalog}) · "
              f"[Source change]({entry.links.source_change})"]
    if not short:
        lines += ["", "<details>", "<summary>Source &amp; validation</summary>", "",
                  text(entry.evidence.test_result)]
        if tests:
            lines += ["", tests]
        if entry.links.related_changes:
            lines += ["", " · ".join(f"[Source {i + 1}]({url})"
                                     for i, url in enumerate(entry.links.related_changes))]
        lines += ["", "</details>", ""]
    if entry.supersedes and not short:
        lines += ["", f"Revision {entry.revision}; supersedes [{entry.supersedes}](#{entry.supersedes})."]
    return "\n".join(lines) + "\n"


def render(entries: list[Entry], readme: str) -> dict[str, str]:
    entries = sorted(entries, key=lambda e: (e.published_at, e.id), reverse=True)
    superseded = {e.supersedes for e in entries if e.supersedes}
    latest = [e for e in entries if e.id not in superseded][:3]
    block = (GENERATED + "\n\n![SURE evaluation release notes](./docs/news/banner.svg)\n\n"
             "## Recently supported\n\n") + "\n".join(
        section(e, prefix="./", short=True) for e in latest)
    block += "\n[Full history](./docs/news/index.md) · [Visual release notes](./docs/news/index.html)\n"
    intro = ("# Release notes\n\n" + GENERATED + "\n\n"
             "![SURE evaluation release notes](banner.svg)\n\n"
             "New evaluation capabilities, their exact pipelines, and the source behind each update.\n\n"
             "[Visual release notes](index.html) · [Latest updates](latest.md)\n\n")
    return {
        "README.md": replace_block(readme, block),
        "docs/news/index.md": intro + "\n---\n\n".join(section(e, prefix="../../") for e in entries),
        "docs/news/latest.md": intro + "\n---\n\n".join(section(e, prefix="../../") for e in latest),
        "docs/news/index.html": render_page(entries),
        "docs/news/banner.svg": render_banner(latest),
    }


def diff(before: dict[str, str], after: dict[str, str]) -> str:
    return "".join("".join(difflib.unified_diff(
        before.get(path, "").splitlines(keepends=True), value.splitlines(keepends=True),
        fromfile="a/" + path, tofile="b/" + path)) for path, value in sorted(after.items()))
